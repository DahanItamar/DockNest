import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp,writeFile,rm } from 'node:fs/promises';
import { createWriteStream } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes } from 'node:crypto';
import { Readable } from 'node:stream';
const root=await mkdtemp(join(tmpdir(),'docknest-evidence-'));
process.env.DATA_DIR=root;process.env.BACKUP_DIR=root;process.env.BACKUP_STORAGE='local';process.env.NODE_ENV='test';
await writeFile(join(root,'master.key'),randomBytes(32).toString('base64'));
const {db}=await import('../src/db.js');
const {recordVerification,backupVerification}=await import('../src/recovery-evidence.js');
const {encryptStream,verifyEncrypted,enqueueScrub,claimJob,executeJob}=await import('../src/engine.js');
test('integrity, declared consistency and application evidence stay independent; failed scrub blocks package use',async()=>{
 const at=new Date().toISOString();
 db.prepare('INSERT INTO servers(id,name,host,port,username,private_key,host_key,created_at) VALUES(?,?,?,?,?,?,?,?)').run('server','Fixture','localhost',22,'root','encrypted','0'.repeat(64),at);
 db.prepare('INSERT INTO sites VALUES(?,?,?,?,?)').run('site','server','Fixture','{}',at);
 db.prepare("INSERT INTO jobs(id,site_id,type,status,stage,created_at) VALUES('capture','site','backup','completed','completed',?)").run(at);
 const file=join(root,'payload.enc');await encryptStream(Readable.from(['private fixture']),createWriteStream(file));
 db.prepare('INSERT INTO backups VALUES(?,?,?,?,?,?,?,?,?,?,?)').run('backup','site','capture',at,file,47,await verifyEncrypted(file),'{}',0,1,at);
 recordVerification('backup','integrity',{status:'passed',method:'authentication'});
 recordVerification('backup','consistency',{status:'declared',method:'operator confirmation'});
 assert.equal(backupVerification('backup').application.status,'not-tested');
 recordVerification('backup','application',{status:'passed',scope:'configured check'});
 recordVerification('backup','application',{status:'failed',scope:'later attempt'});
 assert.equal(backupVerification('backup').integrity.status,'passed');
 assert.equal(db.prepare("SELECT COUNT(*) AS n FROM backup_verification_history WHERE backup_id='backup' AND kind='application'").get().n,2);
 const bytes=await import('node:fs/promises').then(fs=>fs.readFile(file));bytes[20]^=1;await writeFile(file,bytes);
 const scrub=enqueueScrub('backup','fixture');assert.equal(claimJob().id,scrub.id);await executeJob(db.prepare('SELECT * FROM jobs WHERE id=?').get(scrub.id));
 assert.equal(backupVerification('backup').integrity.status,'failed');
 assert.equal(db.prepare("SELECT verified FROM backups WHERE id='backup'").get().verified,0);
 assert.equal(db.prepare('SELECT status FROM jobs WHERE id=?').get(scrub.id).status,'failed');
 db.close();await rm(root,{recursive:true,force:true});
});
